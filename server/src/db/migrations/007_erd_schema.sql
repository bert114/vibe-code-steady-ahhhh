-- 007: replace the MVP check-in schema with the user-provided ERD.
-- This is a destructive cutover: existing application data is discarded.

DROP TABLE IF EXISTS recovery_sessions, ai_boundary_messages, social_interactions,
  weekly_summaries, coping_activities, daily_logs, boundary_templates,
  relationship_types CASCADE;

DROP TABLE IF EXISTS users CASCADE;

DROP TYPE IF EXISTS effort_level CASCADE;

CREATE TYPE effort_level AS ENUM ('low', 'medium', 'high');

CREATE TABLE users (
  clerk_id VARCHAR PRIMARY KEY,
  email VARCHAR UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE daily_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR NOT NULL REFERENCES users(clerk_id) ON DELETE CASCADE,
  log_date DATE NOT NULL,
  battery_level SMALLINT NOT NULL CHECK (battery_level BETWEEN 1 AND 5),
  mood_score SMALLINT NOT NULL CHECK (mood_score BETWEEN 1 AND 5),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE weekly_summaries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR NOT NULL REFERENCES users(clerk_id) ON DELETE CASCADE,
  week_start DATE NOT NULL,
  summary TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE relationship_types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR NOT NULL UNIQUE
);

CREATE TABLE coping_activities (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id VARCHAR NOT NULL REFERENCES users(clerk_id) ON DELETE CASCADE,
  name VARCHAR NOT NULL,
  effort_level effort_level NOT NULL,
  success_score NUMERIC,
  usage_count INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE social_interactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  daily_log_id INTEGER NOT NULL REFERENCES daily_logs(id) ON DELETE CASCADE,
  relationship_type_id INTEGER NOT NULL REFERENCES relationship_types(id) ON DELETE RESTRICT,
  custom_name VARCHAR,
  duration_minutes INTEGER NOT NULL CHECK (duration_minutes >= 0),
  drain_score INTEGER NOT NULL CHECK (drain_score BETWEEN 1 AND 5),
  interaction_time TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE boundary_templates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category VARCHAR NOT NULL,
  title VARCHAR NOT NULL,
  template TEXT NOT NULL
);

CREATE TABLE ai_boundary_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  interaction_id INTEGER NOT NULL REFERENCES social_interactions(id) ON DELETE CASCADE,
  template_id INTEGER NOT NULL REFERENCES boundary_templates(id) ON DELETE RESTRICT,
  generated_message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE recovery_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  interaction_id INTEGER NOT NULL REFERENCES social_interactions(id) ON DELETE CASCADE,
  activity_id INTEGER NOT NULL REFERENCES coping_activities(id) ON DELETE CASCADE,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX daily_logs_user_date_idx ON daily_logs (user_id, log_date DESC);
CREATE INDEX weekly_summaries_user_week_idx ON weekly_summaries (user_id, week_start DESC);
CREATE INDEX coping_activities_user_idx ON coping_activities (user_id);
CREATE INDEX social_interactions_daily_log_idx ON social_interactions (daily_log_id);
CREATE INDEX social_interactions_relationship_idx ON social_interactions (relationship_type_id);
CREATE INDEX ai_boundary_messages_interaction_idx ON ai_boundary_messages (interaction_id);
CREATE INDEX ai_boundary_messages_template_idx ON ai_boundary_messages (template_id);
CREATE INDEX recovery_sessions_interaction_idx ON recovery_sessions (interaction_id);
CREATE INDEX recovery_sessions_activity_idx ON recovery_sessions (activity_id);
